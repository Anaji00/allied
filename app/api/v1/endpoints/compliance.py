"""FastAPI endpoints for MTR Mill Test Reports, Heat Verification, Certificate of Conformance (CofC), and Non-Conformance Reports (NCR)."""

from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status

from app.models.compliance_mtr import (
    CertificateOfConformance,
    DispositionNCRRequest,
    MTRRecord,
    MTRVerifyRequest,
    NCRRecord,
)
from app.core.security import require_operator, require_viewer
from app.services.mtr_service import mtr_service

router = APIRouter()


@router.get(
    "/mtr/{heat_number}",
    response_model=MTRRecord,
    summary="Retrieve certified Material Test Report (MTR) by Heat Number",
)
def get_mtr_by_heat_number(
    heat_number: str,
    _user: dict = Depends(require_viewer),
) -> MTRRecord:
    """Returns chemical analysis, mechanical hardness tests, and ASTM compliance for a heat number."""
    mtr = mtr_service.get_mtr_by_heat(heat_number)
    if not mtr:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"MTR for heat number {heat_number} not found",
        )
    return mtr


@router.post(
    "/mtr/verify",
    response_model=MTRRecord,
    summary="Verify and register inbound supplier mill test report",
)
def verify_supplier_mtr(
    request: MTRVerifyRequest,
    current_user: dict = Depends(require_operator),
) -> MTRRecord:
    """Audits OCR chemistry and mechanical data against ASTM standard tolerance envelope.

    Registering a cert replaces the one on file for the heat, so it needs
    OPERATOR+ and the actor is recorded in the audit trail.
    """
    try:
        return mtr_service.verify_and_register_mtr(
            request,
            actor_email=current_user.get("email", "system"),
            actor_role=current_user.get("role", "SYSTEM"),
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"MTR verification failed: {str(exc)}",
        )


@router.get(
    "/cofc/{sales_order_number}",
    response_model=CertificateOfConformance,
    summary="Generate audited Certificate of Conformance (CofC) bundle for a customer order",
)
def get_order_certificate_of_conformance(
    sales_order_number: str,
    customer_id: Optional[str] = Query("10221"),
    customer_name: Optional[str] = Query("Owens Corning"),
    customer_po_number: Optional[str] = Query("PO-CERT-1001"),
    heat_numbers: Optional[str] = Query("HT-300XL-8819", description="Comma-separated heat numbers"),
    _user: dict = Depends(require_viewer),
) -> CertificateOfConformance:
    """Produces digital CofC certifying material compliance and bundled MTR chemical analyses."""
    try:
        heats = [h.strip() for h in heat_numbers.split(",") if h.strip()]
        return mtr_service.generate_cofc(
            sales_order_number=sales_order_number,
            customer_id=customer_id,
            customer_name=customer_name,
            customer_po_number=customer_po_number,
            heat_numbers=heats,
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"CofC generation failed: {str(exc)}",
        )


@router.get(
    "/ncr",
    response_model=List[NCRRecord],
    summary="List Non-Conformance Reports (NCR) for quarantined materials",
)
def list_ncrs(
    status_filter: Optional[str] = Query(None, description="QUARANTINED, REJECTED, CONCESSION_APPROVED, CLOSED")
,
    _user: dict = Depends(require_viewer),
) -> List[NCRRecord]:
    """Returns active or historic Non-Conformance Reports generated by ASTM audits."""
    return mtr_service.list_ncrs(status_filter=status_filter)


@router.get(
    "/ncr/{ncr_id}",
    response_model=NCRRecord,
    summary="Retrieve single Non-Conformance Report by ID",
)
def get_ncr_by_id(
    ncr_id: str,
    _user: dict = Depends(require_viewer),
) -> NCRRecord:
    """Returns full details of an NCR including metallurgy failures and disposition history."""
    ncr = mtr_service.get_ncr(ncr_id)
    if not ncr:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"NCR {ncr_id} not found",
        )
    return ncr


@router.post(
    "/ncr/{ncr_id}/disposition",
    response_model=NCRRecord,
    summary="Disposition a quarantined Non-Conformance Report (concession or return)",
)
def disposition_ncr(
    ncr_id: str,
    request: DispositionNCRRequest,
    current_user: dict = Depends(require_operator),
) -> NCRRecord:
    """Executes disposition action (RETURN_TO_SUPPLIER, APPROVE_CONCESSION, REQUEST_LAB_RETEST).

    The actor recorded on the NCR and in the audit trail comes from the bearer
    token, never from the request body.
    """
    try:
        return mtr_service.disposition_ncr(
            ncr_id, request, actor_email=current_user["email"]
        )
    except KeyError:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"NCR {ncr_id} not found",
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Failed to disposition NCR: {str(exc)}",
        )
